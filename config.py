DEFAULTS = {name: default for _, name, default, _ in SETTINGS}
globals().update(DEFAULTS)


def user_config_path() -> str:
    return os.path.join(os.environ.get("APPDATA") or os.path.expanduser("~"), "TesseraWall", "config.toml")


def migrate_old_settings() -> bool:
    """Tessera Wall was called mpvwall before its first public release. If this user has settings from
    then and none under the new name, copy them across once (the old folder is left alone)."""
    new = os.path.dirname(user_config_path())
    old = os.path.join(os.path.dirname(new), "mpv" + "wall")
    if os.path.isdir(old) and not os.path.exists(new):
        try:
            shutil.copytree(old, new)
            return True
        except OSError:
            pass
    return False


def _toml(value) -> str:
    if value is None:
        return '""'
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if isinstance(value, (set, list)):
        return "[" + ", ".join(_toml(v) for v in sorted(value)) + "]"
    return repr(value)


def template() -> str:
    """Text of a settings file with every setting present but commented out at its default."""
    lines = ["# Tessera Wall settings. Remove the leading '#' from a line and change the value.",
             "# Press F5 in the wall to apply changes without restarting.", ""]
    section = None
    for sec, name, default, doc in SETTINGS:
        if sec != section:
            section = sec
            lines += [f"# ---- {sec} " + "-" * (60 - len(sec)), ""]
        lines += ["# " + d for d in doc.split("\n")]
        lines += [f"# {name.lower()} = {_toml(default)}", ""]
    return "\n".join(lines)


def ensure_user_file(path: str) -> None:
    """Create the commented template if there is no settings file yet. Never overwrites."""
    if os.path.exists(path):
        return
    try:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(template())
    except OSError:
        pass  # read-only location: the defaults still work


def _coerce(name: str, value):
    """Return value converted to the type of the default for `name`, or raise ValueError."""
    default = DEFAULTS[name]
    if default is None:                                   # optional path
        if isinstance(value, str):
            return value or None
    elif isinstance(default, bool):
        if isinstance(value, bool):
            return value
    elif isinstance(default, int):
        if isinstance(value, int) and not isinstance(value, bool):
            return value
    elif isinstance(default, float):
        if isinstance(value, (int, float)) and not isinstance(value, bool):
            return float(value)
    elif isinstance(default, str):
        if isinstance(value, str):
            return value
    elif isinstance(default, (set, list)):
        if isinstance(value, list) and all(isinstance(v, str) for v in value):
            return {v.lower() for v in value} if isinstance(default, set) else list(value)
    raise ValueError(f"{name.lower()} should be {type(default).__name__ if default is not None else 'text'}, "
                     f"got {value!r}")


def load(path: str) -> tuple[list[str], list[str]]:
    """Apply the user's settings file on top of the defaults.

    Returns (names whose value changed, problems). A file that cannot be parsed raises
    (tomllib.TOMLDecodeError / OSError) and changes nothing. A bad or unknown key is skipped and
    reported in problems; the other keys still apply. A missing file means "all defaults".
    """
    data: dict = {}
    if os.path.exists(path):
        with open(path, "rb") as f:
            data = tomllib.load(f)
    new, problems = dict(DEFAULTS), []
    for key, value in data.items():
        name = key.upper()
        if name not in DEFAULTS:
            problems.append(f"unknown setting: {key}")
            continue
        try:
            new[name] = _coerce(name, value)
        except ValueError as e:
            problems.append(str(e))
    changed = [n for n, v in new.items() if globals()[n] != v]
    globals().update(new)
    return changed, problems


def set_user_values(path: str, values: dict) -> None:
    """Write settings into the user's file, touching only their own lines.

    values: {NAME: value}, or {NAME: None} to go back to the default. An existing line for the key is
    rewritten in place (the commented-out line from the template counts, so the file keeps its
    order and descriptions); a key with no line is appended. Everything else, including the user's
    other settings and comments, is left exactly as it was. Only single-line values are supported.
    """
    ensure_user_file(path)
    try:
        with open(path, encoding="utf-8") as f:
            text = f.read()
    except OSError:
        text = ""
    for name, value in values.items():
        key = name.lower()
        line = f"# {key} = {_toml(DEFAULTS[name])}" if value is None else f"{key} = {_toml(value)}"
        m = (re.search(rf"(?m)^[ \t]*{key}[ \t]*=.*$", text)            # the live line, if there is one
             or re.search(rf"(?m)^[ \t]*#[ \t]*{key}[ \t]*=.*$", text))  # else the commented template line
        if m:
            text = text[:m.start()] + line + text[m.end():]
        elif value is not None:
            text = text.rstrip("\n") + ("\n" if text.strip() else "") + line + "\n"
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def app_dir() -> str:
    """Folder the program lives in: next to the .exe in a packaged build, else next to this file."""
    return os.path.dirname(sys.executable if getattr(sys, "frozen", False) else os.path.abspath(__file__))


def find_mpv() -> str | None:
    """Path to mpv.exe: the mpv_path setting, then the copy shipped with tesserawall, then one the user
    installed themselves (PATH and the usual install folders)."""
    if MPV_PATH:
        return MPV_PATH if os.path.isfile(MPV_PATH) else None
    bundled = os.path.join(app_dir(), "mpv", "mpv.exe")   # installed builds carry their own mpv
    if os.path.isfile(bundled):
        return bundled
    env = os.environ
    home = os.path.expanduser("~")
    candidates = [
        os.path.join(home, "scoop", "apps", "mpv", "current", "mpv.exe"),   # real exe, not the scoop shim
        os.path.join(home, "scoop", "apps", "mpv-git", "current", "mpv.exe"),
        shutil.which("mpv"),
        os.path.join(env.get("ProgramFiles", r"C:\Program Files"), "mpv", "mpv.exe"),
        os.path.join(env.get("ProgramFiles(x86)", r"C:\Program Files (x86)"), "mpv", "mpv.exe"),
        os.path.join(env.get("LOCALAPPDATA", ""), "Programs", "mpv", "mpv.exe"),
        os.path.join(env.get("ProgramData", r"C:\ProgramData"), "chocolatey", "lib", "mpv.install", "tools", "mpv.exe"),
        r"C:\mpv\mpv.exe",
        os.path.join(home, "mpv", "mpv.exe"),
    ]
    try:  # installers that register an "App Paths" entry
        import winreg
        for hive in (winreg.HKEY_CURRENT_USER, winreg.HKEY_LOCAL_MACHINE):
            try:
                with winreg.OpenKey(hive, r"Software\Microsoft\Windows\CurrentVersion\App Paths\mpv.exe") as k:
                    candidates.insert(0, winreg.QueryValue(k, None))
            except OSError:
                pass
    except ImportError:
        pass
    for c in candidates:
        if c and os.path.isfile(c):
            return os.path.abspath(c)
    return None


